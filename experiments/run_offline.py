"""Run every experiment that needs no hardware, then write SUMMARY.md.

    python experiments/run_offline.py

Runs: worked_examples.py, gaming_table.py, e3_scheduling.py, e4_deadzone.py.
E1 needs the real laptop, so it is listed as PENDING until
experiments/results/e1.json exists (mock dry runs do not count).
"""

from __future__ import annotations

import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "experiments" / "results"
SCRIPTS = ["worked_examples.py", "gaming_table.py", "e3_scheduling.py", "e4_deadzone.py"]
PENDING = "PENDING (run on the laptop)"


def run_scripts() -> dict[str, int]:
    codes = {}
    for script in SCRIPTS:
        print(f"--- {script}", flush=True)
        proc = subprocess.run([sys.executable, str(ROOT / "experiments" / script)], cwd=ROOT)
        codes[script] = proc.returncode
    return codes


def load(name: str):
    path = RESULTS / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def e1_real() -> dict | None:
    data = load("e1.json")
    return data if data and not data.get("mock") else None


def summary_lines(codes: dict[str, int]) -> list[str]:
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    lines = ["# Results summary", "", f"Generated by `experiments/run_offline.py` at {now}.", "",
             "| experiment | file | status | kind |", "|---|---|---|---|"]
    entries = [
        ("Worked examples (A, C, D)", "worked_examples.json", "computed by compute_settlement"),
        ("Gaming table", "gaming_table.csv", "simulated"),
        ("E3 scheduling benefit", "e3.json", "simulated"),
        ("E4 dead-zone sweep", "e4.json", "simulated"),
    ]
    for label, name, kind in entries:
        status = "present" if (RESULTS / name).exists() else "MISSING"
        lines.append(f"| {label} | `{name}` | {status} | {kind} |")
    e1 = e1_real()
    lines.append(f"| E1 repeatability | `e1.json` | {'present (' + e1['created_at'] + ')' if e1 else PENDING} | "
                 "real laptop measurement |")
    lines += ["", "## Headlines (read from the files above)", ""]

    e3 = load("e3.json")
    if e3:
        pick = {(r["delay_h"], r["forecast_error"], r["defer_z"]): r for r in e3["rows"]}
        for key in ((6, 0.1, 1.0), (12, 0.1, 1.0)):
            r = pick[key]
            lines.append(f"- E3 (simulated): delay {key[0]} h, forecast error {key[1]:.0%}, z = {key[2]:g}: "
                         f"{r['change_pct']:+.1f} % gCO2e per job vs immediate, mean wait {r['mean_wait_h']:.2f} h, "
                         f"{r['share_deferrals_backfired']:.0%} of deferrals backfired.")
    e4 = load("e4.json")
    if e4:
        by = {(r["k"], r["true_gain"]): r for r in e4["rows"]}
        lines.append(f"- E4 (simulated): at k = 1 the false-reward rate (true gain 0) is "
                     f"{by[(1.0, 0.0)]['reward_rate']:.1%}; the reward rate is {by[(1.0, 0.2)]['reward_rate']:.1%} "
                     f"at a true 20 % gain and {by[(1.0, 0.4)]['reward_rate']:.1%} at 40 %.")
    gt = RESULTS / "gaming_table.csv"
    if gt.exists():
        import csv
        rows = list(csv.DictReader(gt.open(encoding="utf-8")))
        ex_post = [float(r["min_net_credits"]) for r in rows if r["rule"].startswith("ex-post")]
        ex_ante_neg = sum(int(r["negative_net_jobs"]) for r in rows if r["rule"] == "ex-ante")
        lines.append(f"- Gaming table (simulated): lowest ex-post net {min(ex_post):.4f} credits; "
                     f"{ex_ante_neg} job(s) with a negative net under the simplified ex-ante strawman.")
    lines.append(f"- E1 (real laptop): " + (
        "; ".join(f"workers {s['workers']}: CV {s['cv']:.1%}, coverage ±1σ {s['coverage_1sigma']:.0%}"
                  for s in e1["summary"]) if e1 else PENDING))
    failed = [s for s, c in codes.items() if c != 0]
    if failed:
        lines += ["", f"**Scripts that failed:** {', '.join(failed)}"]
    return lines


def main() -> int:
    codes = run_scripts()
    text = "\n".join(summary_lines(codes)) + "\n"
    (RESULTS / "SUMMARY.md").write_text(text, encoding="utf-8")
    print("\n" + text)
    return 1 if any(codes.values()) else 0


if __name__ == "__main__":
    sys.exit(main())
